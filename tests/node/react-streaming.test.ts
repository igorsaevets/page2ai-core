// BL-39 (T126): React streaming SSR. Next.js App Router, Remix and Mintlify send the shell with a Suspense fallback,
// `<!--$?--><template id="B:0"></template>fallback<!--/$-->`, and the late content at the end of <body> as
// `<div hidden id="S:0">` plus `<script>$RC("B:0","S:0")</script>`, which moves it into the boundary in a browser.
// Measured: the benchmark's docs.anthropic.com page (captured 2026-07-28) printed 212 characters of "Loading..." for a
// 12,270-character article; 7 of 16 fresh Next.js / Mintlify / Remix pages stream this way, and on vercel.com/docs the
// code tabs and the framework picker inside <main> arrive as segments. Chromium served each saved page with only its
// inline scripts gave, through the converter, byte for byte what the replay gives (8 of 8 pages; audit
// `.memory/audits/T126-2026-10-16/scripts/stream_oracle.mjs`).
// T127 (the T126 panel): a call counts only where a browser runs it. The first guard group was run in Chromium 149 with
// React's own runtime, which keeps the fallback there too (`.memory/audits/T127-2026-10-16/scripts/panel_browser.py`);
// from "a script that is not JavaScript" on, the T126 build had moved the hidden segment into the root. The second
// group is markup React does not write, left as it stands, where React's runtime, which checks none of it, moves it.

import { describe, expect, it } from 'vitest';
import { htmlToMarkdown } from '../../src/node/index.js';

const md = (html: string, extra: Record<string, unknown> = {}): string =>
  htmlToMarkdown(html, { baseUrl: 'https://example.test/', includeFrontmatter: false, ...extra }).markdown.trim();

const page = (main: string, tail = ''): string =>
  `<html><body><header><p>Site</p></header><main>${main}</main>${tail}</body></html>`;
const BOUNDARY = '<!--$?--><template id="B:0"></template><p>Loading...</p><!--/$-->';
const LATE = '<div hidden id="S:0"><h1>Title</h1><p>Body</p></div>';
const RC = '<script>$RC("B:0","S:0")</script>';

// React's own inline runtimes, so a fixture is the code a browser runs (the T126 file had a stub that queued the reveal
// and never ran it: Chromium kept "Loading..." on it). react-dom 19.2.0, ReactDOMFizzInstructionSetInlineCodeStrings.js
// `completeBoundary` (MIT, Meta Platforms, Inc.), which the benchmark page carries; react-dom 18's `$RC` as remix.run
// serves it (2026-10-16). Generated by `.memory/audits/T127-2026-10-16/scripts/runtime_literals.mjs`.
const RUNTIME_19_2 =
  '$RB=[];$RV=function(a){$RT=performance.now();for(var b=0;b<a.length;b+=2){var c=a[b],e=a[b+1];null!='
  + '=e.parentNode&&e.parentNode.removeChild(e);var f=c.parentNode;if(f){var g=c.previousSibling,h=0;do{i'
  + 'f(c&&8===c.nodeType){var d=c.data;if("/$"===d||"/&"===d)if(0===h)break;else h--;else"$"!==d&&"$?"!=='
  + 'd&&"$~"!==d&&"$!"!==d&&"&"!==d||h++}d=c.nextSibling;f.removeChild(c);c=d}while(c);for(;e.firstChild;'
  + ')f.insertBefore(e.firstChild,c);g.data="$";g._reactRetry&&requestAnimationFrame(g._reactRetry)}}a.le'
  + 'ngth=0};\n$RC=function(a,b){if(b=document.getElementById(b))(a=document.getElementById(a))?(a.previou'
  + 'sSibling.data="$~",$RB.push(a,b),2===$RB.length&&("number"!==typeof $RT?requestAnimationFrame($RV.bi'
  + 'nd(null,$RB)):(a=performance.now(),setTimeout($RV.bind(null,$RB),2300>a&&2E3<a?2300-a:$RT+300-a)))):'
  + 'b.parentNode.removeChild(b)};';
const RUNTIME_18 =
  'function $RC(a,b){a=document.getElementById(a);b=document.getElementById(b);b.parentNode.removeChild'
  + '(b);if(a){a=a.previousSibling;var f=a.parentNode,c=a.nextSibling,e=0;do{if(c&&8===c.nodeType){var d='
  + 'c.data;if("/$"===d)if(0===e)break;else e--;else"$"!==d&&"$?"!==d&&"$!"!==d||e++}d=c.nextSibling;f.re'
  + 'moveChild(c);c=d}while(c);for(;b.firstChild;)f.insertBefore(b.firstChild,c);a.data="$";a._reactRetry'
  + '&&a._reactRetry()}}';

describe('BL-39: a streamed segment goes where the page\'s own script puts it', () => {
  it.each([
    ['the Mintlify shape: the article after <main> fills its boundary, the fallback goes',
      page(`<p>Before</p>${BOUNDARY}<p>After</p>`, LATE + RC), 'Before\n\n# Title\n\nBody\n\nAfter'],
    ['React 19.2\'s runtime and the call in one script, as the benchmark page sends them',
      page(BOUNDARY, `${LATE}<script>${RUNTIME_19_2};$RC("B:0","S:0")</script>`), '# Title\n\nBody'],
    ['React 18\'s runtime, a function declaration, as remix.run sends it',
      page(BOUNDARY, `${LATE}<script>${RUNTIME_18};$RC("B:0","S:0")</script>`), '# Title\n\nBody'],
    ['a boundary React 19.2 has already queued (`$~`), as a page saved mid-reveal has it',
      page('<!--$~--><template id="B:0"></template><p>Loading...</p><!--/$-->', LATE + RC), '# Title\n\nBody'],
    ['a fallback holding a finished boundary goes up to its own closing comment',
      page('<!--$?--><template id="B:0"></template><!--$--><p>inner</p><!--/$--><p>fallback</p><!--/$--><p>After</p>',
        LATE + RC), '# Title\n\nBody\n\nAfter'],
    ['an identifierPrefix, and boundary and segment numbers that differ',
      page('<!--$?--><template id="app-B:1"></template><p>Loading...</p><!--/$-->',
        '<div hidden id="app-S:2a"><p>Late</p></div><script>$RC("app-B:1","app-S:2a")</script>'), 'Late'],
    ['a boundary inside a streamed segment, filled in stream order',
      page(BOUNDARY, '<div hidden id="S:0"><p>Outer</p><!--$?--><template id="B:1"></template><p>Loading 2</p><!--/$--></div>'
        + RC + '<div hidden id="S:1"><p>Inner</p></div><script>$RC("B:1","S:1")</script>'), 'Outer\n\nInner'],
    ['calls run in document order: the first fills the boundary, a later one for it drops its segment',
      page(`${BOUNDARY}<div hidden id="S:1"><p>Two</p></div>`, '<div hidden id="S:0"><p>One</p></div>'
        + '<script>$RC("B:0","S:0")</script><script>$RC("B:0","S:1")</script>'), 'One'],
    ['a module script runs after the classic ones, and then its boundary is gone',
      page(BOUNDARY, '<div hidden id="S:0"><p>One</p></div><div hidden id="S:1"><p>Two</p></div>'
        + '<script type="module">$RC("B:0","S:0")</script><script>$RC("B:0","S:1")</script>'), 'Two'],
    ['a script with a JavaScript type, a language attribute or a nonce runs like a bare one',
      page(BOUNDARY, `${LATE}<script type="text/javascript" nonce="n" language="javascript">$RC("B:0","S:0")</script>`),
      '# Title\n\nBody'],
    ['$RS puts a segment on its placeholder',
      page('<p>A</p><template id="P:1"></template><p>C</p>', '<div hidden id="S:1"><p>B</p></div><script>$RS("S:1","P:1")</script>'),
      'A\n\nB\n\nC'],
    ['$RR (a boundary waiting for stylesheets) fills it like $RC',
      page(BOUNDARY, LATE + '<script>$RR("B:0","S:0",[["/a.css","high"]])</script>'), '# Title\n\nBody'],
    ['rows streamed into a table body',
      page('<table><thead><tr><th>h</th></tr></thead><tbody><!--$?--><template id="B:0"></template><!--/$--></tbody></table>',
        '<table hidden><tbody id="S:0"><tr><td>v</td></tr></tbody></table>' + RC), '| h |\n| --- |\n| v |'],
    ['a MathML segment, which React wraps in <math aria-hidden="true" style="display:none">',
      page('<math><!--$?--><template id="B:0"></template><mtext>Loading</mtext><!--/$--></math>',
        '<math aria-hidden="true" style="display:none" id="S:0"><mtext>Late</mtext></math>' + RC), 'Late'],
    ['a segment whose boundary is gone is dropped, as React drops it',
      page('<p>A</p><div hidden id="S:0"><p>orphan</p></div>', '<script>$RC("B:9","S:0")</script>'), 'A'],
    ['a boundary the parser reaches only after the script is gone for it, so the segment is dropped',
      page(`<div hidden id="S:0"><p>orphan</p></div>${RC}${BOUNDARY}`), 'Loading...'],
  ])('%s', (_label, html, expected) => {
    expect(md(html)).toBe(expected);
  });

  it('includeHidden: true places it the same way', () => {
    expect(md(page(`<p>Before</p>${BOUNDARY}<p>After</p>`, LATE + RC), { includeHidden: true }))
      .toBe('Before\n\n# Title\n\nBody\n\nAfter');
  });

  it.each([
    ['$RC whose boundary is gone', page('<p>A</p><div hidden id="S:0"><p>orphan</p></div>', '<script>$RC("B:9","S:0")</script>')],
    ['$RS whose placeholder is gone', page('<p>A</p><div hidden id="S:1"><p>orphan</p></div>', '<script>$RS("S:1","P:9")</script>')],
  ])('includeHidden: true still drops the segment of %s, as React removes it', (_label, html) => {
    expect(md(html, { includeHidden: true })).toBe('A');
  });

  it.each([
    ['a call inside an escaped string (an RSC payload)',
      page(BOUNDARY, LATE + '<script>self.__next_f.push([1,"$RC(\\"B:0\\",\\"S:0\\")"])</script>')],
    ['$RX (client rendering) keeps the fallback', page(BOUNDARY, LATE + '<script>$RX("B:0","digest")</script>')],
    ['a script that is not JavaScript', page(BOUNDARY, LATE + '<script type="application/json">$RC("B:0","S:0")</script>')],
    ['a script whose type is text/plain', page(BOUNDARY, LATE + '<script type="text/plain">$RC("B:0","S:0")</script>')],
    ['a script in <noscript>', page(BOUNDARY, `${LATE}<noscript>${RC}</noscript>`)],
    ['the text of a script with src', page(BOUNDARY, LATE + '<script src="/runtime.js">$RC("B:0","S:0")</script>')],
    ['a nomodule script', page(BOUNDARY, LATE + '<script nomodule>$RC("B:0","S:0")</script>')],
    ['a call in a comment', page(BOUNDARY, LATE + '<script>/*$RC("B:0","S:0")*/</script>')],
    ['a call in a string', page(BOUNDARY, LATE + '<script>var s=\'$RC("B:0","S:0")\';</script>')],
    ['a call that does not start a statement', page(BOUNDARY, LATE + '<script>if(false)$RC("B:0","S:0")</script>')],
    ['a segment the parser reaches only after the script', page(BOUNDARY, RC + LATE)],
    ['a segment inside <template> contents', page(BOUNDARY, `<template>${LATE}</template>${RC}`)],
  ])('guard: %s', (_label, html) => {
    expect(md(html)).toBe('Loading...');
  });

  it.each([
    ['a template with no pending comment before it is no boundary',
      page('<template id="B:0"></template><p>Loading...</p><!--/$-->', LATE + RC), 'Loading...'],
    ['a boundary with no closing comment removes nothing',
      page('<!--$?--><template id="B:0"></template><p>Loading...</p>', LATE + RC), 'Loading...'],
    ['a hidden element that is not one of React\'s segment wrappers is not moved',
      page(BOUNDARY, '<section hidden id="S:0"><h1>Title</h1></section>' + RC), 'Loading...'],
    ['a visible element with a segment id is not moved',
      page(`<div id="S:0"><p>Visible</p></div>${BOUNDARY}`, RC), 'Visible\n\nLoading...'],
    ['a segment holding its own boundary is left alone',
      page('<p>A</p>', '<div hidden id="S:0"><!--$?--><template id="B:0"></template><!--/$--><p>x</p></div>' + RC), 'A'],
  ])('guard, markup React does not write: %s', (_label, html, expected) => {
    expect(md(html)).toBe(expected);
  });
});
